  function apply(lang) {
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    var node;
    while ((node = walker.nextNode())) {
      var tag = node.parentNode.nodeName;
      if (tag === "SCRIPT" || tag === "STYLE" || tag === "BUTTON" && node.parentNode.id === "lang") continue;
      var raw = originals.has(node) ? originals.get(node) : node.nodeValue;
      var key = raw.trim();
      if (!key || !Object.prototype.hasOwnProperty.call(HI, key)) continue;
      if (!originals.has(node)) originals.set(node, raw);
      node.nodeValue = lang === "hi" ? raw.replace(key, HI[key]) : originals.get(node);
    }
    var labelled = document.querySelectorAll("[aria-label]");
    for (var i = 0; i < labelled.length; i++) {
      var el = labelled[i];
      if (el.id === "lang") continue;
      if (!el.hasAttribute("data-en-label")) el.setAttribute("data-en-label", el.getAttribute("aria-label"));
      var en = el.getAttribute("data-en-label");
      el.setAttribute("aria-label", lang === "hi" && HI[en] ? HI[en] : en);
    }
    document.documentElement.lang = lang;
    document.title = lang === "hi" ? TITLE_HI : TITLE_EN;
    if (btn) {
      btn.textContent = lang === "hi" ? "English" : "हिन्दी";
      btn.setAttribute("lang", lang === "hi" ? "en" : "hi");
      btn.setAttribute("aria-label", lang === "hi" ? "Switch to English" : "हिन्दी में देखें");
    }
  }

